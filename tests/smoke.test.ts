import assert from 'node:assert/strict';
import {execute} from '../src/cli.ts';
import {writeFileSync,readFileSync,unlinkSync} from 'node:fs';

execute('init 400 200');
assert.match(execute('create g flow')!,/g#flow created/);
assert.match(execute('create rect start 30 70 120 60 #4a90d9 in flow')!,/created in g#flow/);
assert.match(execute('create text label 60 100 "Hello world" in flow')!,/created in g#flow/);
assert.match(execute('move flow 10 20')!,/moved/);
assert.match(execute('tree')!,/g#flow[\s\S]*rect#start/);
execute('undo'); assert.match(execute('tree')!,/x=30 y=70/);
execute('redo'); assert.match(execute('tree')!,/x=40 y=90/);
assert.throws(()=>execute('scale flow 0'),/scale factor must be positive/);
assert.match(execute('set label text "Changed text"')!,/updated/);
const file='tests/tmp.svg';execute(`save ${file}`);const xml=readFileSync(file,'utf8');assert.match(xml,/<svg/);unlinkSync(file);
writeFileSync(file,'<svg width="100" height="80"><rect x="1" y="2" width="3" height="4"/></svg>');const read=execute(`read ${file}`)!;assert.match(read,/warning: assigned id rect1/);unlinkSync(file);
execute('init 120 80');
assert.match(execute('create text keyword 0 12 "in"')!,/text#keyword created/);
const beforeInvalidCreate=execute('tree');
assert.throws(()=>execute('create rect broken 1 2 3 4 red extra'),/invalid parameters for rect/);
assert.throws(()=>execute('create rect broken 1 2 3 4 in'),/in requires a container id/);
assert.equal(execute('tree'),beforeInvalidCreate);
assert.throws(()=>execute('set keyword text'),/set requires id, attribute and value/);
execute('init 300 180');
execute('create g outer');
execute('create g inner in outer');
execute('create rect left 10 10 20 20 red in inner');
execute('create circle right 60 20 8 blue in inner');
assert.match(execute('group pair left right')!,/g#pair created with 2 children/);
assert.match(execute('tree')!,/g#inner[\s\S]*g#pair[\s\S]*rect#left[\s\S]*circle#right/);
execute('undo'); assert.match(execute('tree')!,/g#inner[\s\S]*rect#left[\s\S]*circle#right/);
execute('redo'); assert.match(execute('tree')!,/g#pair/);
assert.match(execute('ungroup pair')!,/ungrouped/);
execute('addto outer left'); assert.match(execute('show left')!,/parent=g#outer/);
execute('undo'); assert.match(execute('show left')!,/parent=g#inner/);
execute('init 200 120');
execute('create rect first 0 0 10 10 red');
execute('create rect second 20 0 10 10 blue');
assert.match(execute('group ordered second first')!,/g#ordered created with 2 children/);
const orderedTree=execute('tree')!;
assert.ok(orderedTree.indexOf('rect#first')<orderedTree.indexOf('rect#second'));
execute('init 90 60');
execute('create rect stable 1 2 3 4 red');
const stableTree=execute('tree');
assert.throws(()=>execute('create rect stable 10 10 5 5 blue'),/id already exists: stable/);
assert.throws(()=>execute('create circle invalid 10 NaN 4'),/cy must be a finite number/);
assert.throws(()=>execute('set stable width -1'),/width must be non-negative/);
assert.equal(execute('tree'),stableTree);
assert.throws(()=>execute('canvas 200'),/canvas requires both width and height/);
assert.equal(execute('canvas'),'canvas 90x60');
console.log('smoke tests passed');
